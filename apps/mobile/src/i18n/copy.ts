const CATALOGS: Record<AppLocale, Record<string, string>> = { en: EN, sv: SV };

export function copy(locale: AppLocale, key: string): string {
  return CATALOGS[locale][key] ?? CATALOGS.en[key] ?? key;
}

/** Device locale → supported app locale; anything else falls back to English. */
export function resolveLocale(preference: "system" | AppLocale, deviceLocale: string | null | undefined): AppLocale {
  if (preference !== "system") return preference;
  return (deviceLocale ?? "").toLowerCase().startsWith("sv") ? "sv" : "en";
}

