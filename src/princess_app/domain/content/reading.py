"""Pure, bounded handwriting descriptor and relation selection.

This module does not authorize a report, image, purchase or Premium job. Its
inputs are saved report facts and versioned registries; wording is owned by
those registries. The baked R1 reading source is installed but the /4 runtime
writer is separately gated and is not enabled by the pure policy loader.
"""
from __future__ import annotations

import copy
from dataclasses import dataclass
from functools import lru_cache
import hashlib
import json
from math import isfinite
from pathlib import Path
from typing import Any, Mapping, Sequence

from .presentation import group_nominees, presentation_registry

MAX_DESCRIPTORS = 12
MAX_RELATIONS = 8
RELATION_POLICY_VERSION = "combination-policy/1"
RELATION_KINDS = frozenset({"CONTRAST", "COOCCURRENCE"})

# The reviewed R1 generator embeds source SHA-256 pins in the copy-only server
# registry. Runtime images contain src/, not authored content/, so independently
# pin the exact generated bytes AND their four original source identities here.
# A new editorial/source version requires a separately reviewed pin change.
_READING_PATH = Path(__file__).with_name("_reading_v2.json")
_READING_SHA256 = "00f2e8d851931486f081e705959b349832a1693cefb92d1f0ef8457faaaee6ee"
# The generated presentation file is separately source-locked too. Existing
# presentation_registry() checks predicates against v1; this pin additionally
# locks the authored v2 words and display labels at this reviewed revision.
_PRESENTATION_SHA256 = "cf2c5ae7a5409ff59bd417a2e305ca5796546ca60f5ea42422970ab8f9ec244c"
_READING_SOURCE_PINS = {
    "presentation": "38db3638402399ee27476fcfdff8de82a3d38d47ba90acf10c26a4f877ade5b4",
    "chapters": "ae09af84f7136cba500c46f2b7bfb6f36354251ba01b2c4685363b3e632c756e",
    "relations": "ba814ddc990456aa41d0e274f00d5d1c6174022093ff459b5e24a73aca51ff8b",
    "manifest": "0461b9934b8df7d0f413db431bff6800b21beb3c792734538f9d48a3cea1fe05",
}
_READING_CHAPTERS = ("slant", "baseline", "spacing", "size", "layout", "ink")
_READING_RELATIONS = (
    "space_direction_contrast", "baseline_direction_contrast", "gap_length_contrast",
    "shape_spacing_contrast", "layout_regularity", "stroke_length_contrast",
)
# Stable IDs are an integration mapping to existing chapter-copy/1 state text,
# not new editorial material or client-side authority.
_READING_STATE_IDS = {
    "NEUTRAL": "content.reading.v2.state.neutral",
    "PARTIAL": "content.reading.v2.state.partial",
    "UNQUALIFIED": "content.reading.v2.state.unqualified",
}
_READING_FIELDS = frozenset({
    "version", "status", "runtime_activation", "presentation_version",
    "chapter_policy_version", "policy_version", "reading_pack_version",
    "source_sha256", "chapters", "states", "relations",
})


def _source_pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for name, value in items:
        if name in result:
            raise ValueError("duplicate reading registry key")
        result[name] = value
    return result


def _reviewed_locales(value: Any, *, max_characters: int = 280) -> bool:
    return (isinstance(value, dict) and set(value) == {"en", "sv"}
            and all(isinstance(copy_text, str) and 0 < len(copy_text.strip())
                    and len(copy_text) <= max_characters for copy_text in value.values()))


@lru_cache(maxsize=1)
def _load_reading_registry() -> dict[str, Any]:
    """Read exact, inactive, source-pinned R1 content from the packaged server.

    The original input files are validated by the build generator. Production
    gets only the generated server registry, so the independently pinned byte
    hash prevents changed copy/predicates from being silently accepted. This
    loads Free copy/relations without authorizing the inactive Premium selector.
    """
    if _READING_PATH.is_symlink() or not _READING_PATH.is_file():
        raise ValueError("reviewed reading-v2 registry is not installed")
    try:
        if _READING_PATH.stat().st_size > 262144:
            raise ValueError("reading-v2 registry exceeds size limit")
        raw = _READING_PATH.read_bytes()
        if hashlib.sha256(raw).hexdigest() != _READING_SHA256:
            raise ValueError("reading-v2 registry byte digest mismatch")
        data = json.loads(
            raw.decode("utf-8"), object_pairs_hook=_source_pairs,
            parse_constant=lambda token: (_ for _ in ()).throw(ValueError("nonfinite reading registry")),
        )
    except (OSError, UnicodeError, json.JSONDecodeError, RecursionError) as exc:
        raise ValueError("reading-v2 registry could not be loaded") from exc
    if (not isinstance(data, dict) or set(data) != _READING_FIELDS
            or data["version"] != "reading-v2-registry/1"
            or data["status"] != "DRAFT_FOR_REVIEW"
            or data["runtime_activation"] is not False
            or data["presentation_version"] != "presentation/2"
            or data["chapter_policy_version"] != "chapter-copy/1"
            or data["policy_version"] != RELATION_POLICY_VERSION
            or data["reading_pack_version"] != "premium-reading/2"
            or data["source_sha256"] != _READING_SOURCE_PINS):
        raise ValueError("reading-v2 registry source/version/inactivity mismatch")
    chapters = data["chapters"]
    if not isinstance(chapters, list) or len(chapters) != len(_READING_CHAPTERS):
        raise ValueError("reading-v2 must provide six ordered chapters")
    for family, row in zip(_READING_CHAPTERS, chapters):
        if (not isinstance(row, dict) or set(row) != {
            "section_id", "family", "title", "neutral_content_id", "neutral",
            "unavailable_content_id", "unavailable",
        } or row["family"] != family or row["section_id"] != f"section.{family}"
                or row["neutral_content_id"] != f"content.chapter.v2.{family}.neutral"
                or row["unavailable_content_id"] != f"content.chapter.v2.{family}.unavailable"
                or any(not _reviewed_locales(row[name]) for name in ("title", "neutral", "unavailable"))):
            raise ValueError("reading-v2 chapter identity/locale drift")
    states = data["states"]
    if (not isinstance(states, dict) or set(states) != set(_READING_STATE_IDS)
            or any(not _reviewed_locales(row) for row in states.values())):
        raise ValueError("reading-v2 state copy/locale drift")
    relations = data["relations"]
    if not isinstance(relations, list) or len(relations) != len(_READING_RELATIONS):
        raise ValueError("reading-v2 relationship catalogue mismatch")
    # The reviewed presentation/2 reader independently freezes all 54 legacy
    # predicates and 64 EN/SV labels. Pin its generated editorial bytes too.
    presentation_path = Path(__file__).with_name("_presentation_v2.json")
    if presentation_path.is_symlink() or not presentation_path.is_file():
        raise ValueError("reviewed presentation/2 registry is not installed")
    try:
        presentation_digest = hashlib.sha256(presentation_path.read_bytes()).hexdigest()
    except OSError as exc:
        raise ValueError("reviewed presentation/2 registry could not be loaded") from exc
    if presentation_digest != _PRESENTATION_SHA256:
        raise ValueError("presentation/2 authored copy byte digest mismatch")
    candidates = {row["candidate_id"]: row["family"]
                  for row in presentation_registry(version="presentation/2")["candidates"]}
    for relation_name, row in zip(_READING_RELATIONS, relations):
        if (not isinstance(row, dict) or set(row) != {
            "relation_id", "kind", "content_id", "required_descriptors", "copy",
        } or row["relation_id"] != f"relation.{relation_name}"
                or row["content_id"] != f"content.relation.v1.{relation_name}"
                or row["kind"] not in RELATION_KINDS
                or not _reviewed_locales(row["copy"])):
            raise ValueError("reading-v2 relation identity/locale drift")
        members = row["required_descriptors"]
        if (not isinstance(members, list) or len(members) != 2
                or any(not isinstance(m, str) or m not in candidates for m in members)
                or len({candidates[m] for m in members}) != 2):
            raise ValueError("reading-v2 relation requires two reviewed feature families")
    return data


def reviewed_reading_sha256() -> str:
    """Return the exact vetted R1 server-registry hash after validating its bytes.

    API admission and workers bind this identity to private /4 jobs. The
    generated draft source never gives permission to activate Premium.
    """
    _load_reading_registry()
    return _READING_SHA256


def reading_registry() -> Mapping[str, Any]:
    """Expose a detached copy, never the cached mutable server authority."""
    return copy.deepcopy(_load_reading_registry())


def reading_state_content_id(state: str) -> str:
    """Stable versioned IDs for existing reviewed NEUTRAL/PARTIAL/UNQUALIFIED copy."""
    if not isinstance(state, str) or state not in _READING_STATE_IDS:
        raise ValueError("unknown reviewed reading state")
    _load_reading_registry()
    return _READING_STATE_IDS[state]


def reading_content_text(content_id: str, locale: str) -> str:
    """Resolve only saved, source-bound Free state/chapter/relation copy."""
    if not isinstance(locale, str) or locale.split("-", 1)[0].lower() not in {"en", "sv"}:
        raise ValueError("unsupported reading locale")
    language = locale.split("-", 1)[0].lower()
    data = _load_reading_registry()
    copy_by_id = {
        _READING_STATE_IDS[state]: localized for state, localized in data["states"].items()
    }
    for row in data["chapters"]:
        copy_by_id[row["neutral_content_id"]] = row["neutral"]
        copy_by_id[row["unavailable_content_id"]] = row["unavailable"]
    for row in data["relations"]:
        copy_by_id[row["content_id"]] = row["copy"]
    if not isinstance(content_id, str) or content_id not in copy_by_id:
        raise KeyError(f"unreviewed reading content {content_id!r}")
    return copy_by_id[content_id][language]


def reading_chapter_title(section_id: str, locale: str) -> str:
    """Read reviewed chapter titles; titles are not extra generated story claims."""
    if not isinstance(locale, str) or locale.split("-", 1)[0].lower() not in {"en", "sv"}:
        raise ValueError("unsupported reading locale")
    for row in _load_reading_registry()["chapters"]:
        if row["section_id"] == section_id:
            return row["title"][locale.split("-", 1)[0].lower()]
    raise KeyError(f"unknown reading chapter {section_id!r}")



@dataclass(frozen=True)
class ReadingDescriptor:
    """A selected existing highlight candidate, with its original fact support."""

    candidate_id: str
    family: str
    correlation_group: str
    content_id: str
    strength: float
    support_fact_ids: tuple[str, ...]
    source_region_ids: tuple[str, ...]


@dataclass(frozen=True)
class ReadingRelation:
    """A reviewed noncausal relationship; never a new measurement or score."""

    relation_id: str
    kind: str
    content_id: str
    descriptor_ids: tuple[str, ...]
    support_fact_ids: tuple[str, ...]


def _facts_by_id(facts: Sequence[Mapping[str, Any]]) -> dict[str, Mapping[str, Any]]:
    if not isinstance(facts, (tuple, list)):
        raise ValueError("reading facts must be a saved ordered sequence")
    by_id: dict[str, Mapping[str, Any]] = {}
    seen_features: set[str] = set()
    for fact in facts:
        if not isinstance(fact, Mapping):
            raise ValueError("reading fact must be a mapping")
        fact_id = fact.get("fact_id")
        feature_id = fact.get("feature_id")
        if (not isinstance(fact_id, str) or not isinstance(feature_id, str)
                or fact_id != f"fact.{feature_id}"
                or fact_id in by_id or feature_id in seen_features):
            raise ValueError("duplicate or unbound reading fact")
        regions = fact.get("source_region_ids")
        if not isinstance(regions, (tuple, list)) or any(
                not isinstance(region, str) or not region for region in regions):
            raise ValueError("reading fact has invalid source region IDs")
        by_id[fact_id] = fact
        seen_features.add(feature_id)
    return by_id


def select_descriptors(
    facts: Sequence[Mapping[str, Any]], registry: Mapping[str, Any],
) -> tuple[ReadingDescriptor, ...]:
    """Select at most twelve factual descriptions using approved highlight rules.

    The supplied presentation registry must match the installed version
    exactly; callers cannot inject a new rule or lower a threshold. Selection
    reuses the existing observed-fact eligibility and per-correlation-group
    winner logic. This function is intentionally pure and has no fallback to
    another version when the requested registry is not installed.
    """
    if not isinstance(registry, Mapping):
        raise ValueError("reading presentation registry must be a mapping")
    version = registry.get("version")
    if not isinstance(version, str):
        raise ValueError("missing reading presentation version")
    try:
        reviewed = presentation_registry(version=version)
    except (ValueError, KeyError, OSError) as exc:
        raise ValueError("reading presentation version is unavailable") from exc
    if registry != reviewed:
        raise ValueError("reading presentation registry differs from reviewed source")

    by_fact = _facts_by_id(facts)
    specifications = {row["candidate_id"]: row for row in reviewed["candidates"]}
    selected = sorted(
        group_nominees(facts, version=version),
        key=lambda candidate: (-candidate.strength, candidate.candidate_id),
    )[:MAX_DESCRIPTORS]
    descriptors: list[ReadingDescriptor] = []
    for candidate in selected:
        spec = specifications[candidate.candidate_id]
        support = tuple(candidate.support_fact_ids)
        if not support or any(fid not in by_fact for fid in support):
            raise ValueError("reading descriptor has foreign fact support")
        regions = tuple(sorted({
            region_id
            for fid in support
            for region_id in by_fact[fid]["source_region_ids"]
        }))
        if not isfinite(candidate.strength) or not 0 <= candidate.strength <= 1:
            raise ValueError("reading descriptor has invalid strength")
        descriptors.append(ReadingDescriptor(
            candidate_id=candidate.candidate_id,
            family=candidate.family,
            correlation_group=spec["correlation_group"],
            content_id=candidate.content_id,
            strength=candidate.strength,
            support_fact_ids=support,
            source_region_ids=regions,
        ))
    return tuple(descriptors)


def select_relations(
    descriptors: Sequence[ReadingDescriptor], registry: Mapping[str, Any],
) -> tuple[ReadingRelation, ...]:
    """Apply only supplied, reviewed relation rules in stable catalogue order.

    A missing operand removes a relationship. Every relationship must involve
    two different feature families and carry the exact union of participating
    fact IDs. The authoritative generator/manifest validates the registry
    before it can be activated; this pure function does not activate it.
    """
    if (not isinstance(registry, Mapping)
            or registry.get("policy_version") != RELATION_POLICY_VERSION):
        raise ValueError("unsupported reading relation policy")
    rules = registry.get("relations")
    if not isinstance(rules, (list, tuple)) or len(rules) > MAX_RELATIONS:
        raise ValueError("invalid reading relation catalogue")
    if not isinstance(descriptors, (tuple, list)) or len(descriptors) > MAX_DESCRIPTORS:
        raise ValueError("invalid reading descriptor selection")
    selected: dict[str, ReadingDescriptor] = {}
    for descriptor in descriptors:
        if not isinstance(descriptor, ReadingDescriptor) or descriptor.candidate_id in selected:
            raise ValueError("invalid or duplicate reading descriptor")
        if (not descriptor.support_fact_ids
                or type(descriptor.strength) not in (int, float)
                or not isfinite(descriptor.strength)
                or any(not isinstance(fid, str) or not fid for fid in descriptor.support_fact_ids)):
            raise ValueError("invalid relation descriptor support")
        selected[descriptor.candidate_id] = descriptor

    results: list[ReadingRelation] = []
    seen_relations: set[str] = set()
    for rule in rules:
        if not isinstance(rule, Mapping):
            raise ValueError("invalid reading relation rule")
        relation_id = rule.get("relation_id")
        kind = rule.get("kind")
        content_id = rule.get("content_id")
        required = rule.get("required_descriptors")
        if (not isinstance(relation_id, str) or not relation_id
                or relation_id in seen_relations
                or not isinstance(kind, str) or kind not in RELATION_KINDS
                or not isinstance(content_id, str) or not content_id
                or not isinstance(required, (list, tuple))
                or len(required) < 2
                or any(not isinstance(cid, str) or not cid for cid in required)
                or len(required) != len(set(required))):
            raise ValueError("invalid or duplicate reading relation")
        seen_relations.add(relation_id)
        if any(cid not in selected for cid in required):
            continue
        operands = [selected[cid] for cid in required]
        if len({operand.family for operand in operands}) < 2:
            raise ValueError("same-family relation is not a cross-feature observation")
        facts = tuple(sorted({
            fact_id for operand in operands for fact_id in operand.support_fact_ids
        }))
        if not facts:
            raise ValueError("reading relation lacks observed fact support")
        results.append(ReadingRelation(
            relation_id=relation_id, kind=kind, content_id=content_id,
            descriptor_ids=tuple(required), support_fact_ids=facts,
        ))
    return tuple(results)
